# 稳定错误模型
#
# 定位
#   领域、应用、CLI 与 API 共享的脱敏错误代码边界
#
# 职责
#   定义稳定 ErrorCode｜保存安全详情｜在构造时统一脱敏
#
# 边界
#   原始异常、秘密和未脱敏输入不得进入公共错误消息或 details。
#
# 调用链
#   Domain / Application / Infrastructure → JiejianError → CLI / API mapping
# =============================================================================

